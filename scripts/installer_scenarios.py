#!/usr/bin/env python3
"""Installation-to-first-use scenarios for the one-line installer (review R5), run end to end with the
REAL installer script and the REAL CLI against loopback fixtures.

Only the package-manager action is stubbed (`uv tool install` → no-op; the CLI runs from this checkout);
the inference backend is the repository's fake backend; every key is generated by `modelsaar init`
inside a temporary home and never leaves the machine. Scenarios:

  1. fresh install       — no config: installer runs `init` against the fixture backend, starts a
                           temporary gateway, `modelsaar test --model auto` passes with attribution
  2. repeat install      — config exists: kept; keys/state untouched; check passes again
  3. unrelated listener  — the configured port is held by a non-ModelSaar HTTP service answering 200:
                           the installer stops, sends NO request carrying the key, and names the collision
  4. running gateway     — a real gateway already serves the port: identified by the health contract,
                           reused for the check, not restarted
  5. first use           — the commands the site prints after the installer: `modelsaar serve` (not
                           `init && serve`), `modelsaar test`, and one client configuration
                           (`modelsaar client-config open-webui`) rendered from the running gateway

Usage: python scripts/installer_scenarios.py [--install site/static/install.sh] [--out DIR]
Exit 0 when every scenario behaves as specified; the transcript is written to DIR.
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import socket
import subprocess
import sys
import tempfile
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from modelsaar.testing.fakebackend import FakeBackend, FakeModel  # noqa: E402


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class Foreign(BaseHTTPRequestHandler):
    calls: list[dict] = []

    def log_message(self, *a):  # noqa: D102
        pass

    def do_GET(self):  # noqa: N802
        Foreign.calls.append({"method": "GET", "path": self.path, "authorization": self.headers.get("Authorization")})
        self.send_response(200)
        self.send_header("Content-Type", "text/plain")
        self.end_headers()
        self.wfile.write(b"Foreign service alive. This is not ModelSaar.")

    def do_POST(self):  # noqa: N802
        self.rfile.read(int(self.headers.get("Content-Length", "0")))
        Foreign.calls.append({"method": "POST", "path": self.path, "authorization": self.headers.get("Authorization")})
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.end_headers()
        self.wfile.write(b'{"choices":[{"message":{"content":"response from an unrelated service"}}]}')


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--install", default=str(ROOT / "site/static/install.sh"))
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    install = Path(a.install).resolve()
    out_dir = Path(a.out) if a.out else Path(tempfile.mkdtemp(prefix="modelsaar-installer-scenarios-"))
    out_dir.mkdir(parents=True, exist_ok=True)
    log = open(out_dir / "transcript.txt", "w", encoding="utf-8")

    def say(*parts):
        line = " ".join(str(p) for p in parts)
        print(line)
        log.write(line + "\n")
        log.flush()

    results: list[dict] = []
    tmp = Path(tempfile.mkdtemp(prefix="modelsaar-inst-"))
    bindir = tmp / "bin"
    bindir.mkdir()
    home = tmp / "home"
    # Package-manager stub: `uv tool dir --bin` -> our bin dir; `uv tool install …` -> no-op (the CLI below is real).
    (bindir / "uv").write_text('#!/bin/sh\nif [ "$1 $2 $3" = "tool dir --bin" ]; then printf "%s\\n" "$MODELSAAR_SCENARIO_BIN"; fi\nexit 0\n')
    (bindir / "uv").chmod(0o755)
    (bindir / "modelsaar").write_text("#!/bin/sh\nexec " + shlex.quote(sys.executable) + ' -m modelsaar.cli "$@"\n')
    (bindir / "modelsaar").chmod(0o755)
    env = {k: v for k, v in os.environ.items() if not k.upper().endswith("_PROXY")}
    env.update({"PATH": f"{bindir}:{env.get('PATH', '')}", "MODELSAAR_SCENARIO_BIN": str(bindir), "MODELSAAR_HOME": str(home),
                "PYTHONPATH": str(ROOT / "src"), "NO_PROXY": "127.0.0.1,localhost"})
    for k in ("MODELSAAR_CONFIG", "MODELSAAR_NO_CHECK", "MODELSAAR_SOURCE", "MODELSAAR_ENDPOINT", "MODELSAAR_TYPE", "MODELSAAR_PORT"):
        env.pop(k, None)

    fake = FakeBackend([FakeModel("small:1b", ["completion", "tools"], 8192, parameter_size="1.0B", loaded=True),
                        FakeModel("plain:3b", ["completion"], 4096, parameter_size="3B")])
    fake.start()
    port = free_port()
    env_fresh = {**env, "MODELSAAR_ENDPOINT": f"http://127.0.0.1:{fake.port}", "MODELSAAR_TYPE": "ollama", "MODELSAAR_PORT": str(port)}

    def run(cmd, e, timeout=120, name=""):
        say(f"\n$ {cmd if isinstance(cmd, str) else ' '.join(shlex.quote(c) for c in cmd)}")
        r = subprocess.run(cmd, shell=isinstance(cmd, str), env=e, capture_output=True, text=True, timeout=timeout)
        say(r.stdout.rstrip())
        if r.stderr.strip():
            say("[stderr] " + r.stderr.rstrip())
        say(f"[exit {r.returncode}]")
        return r

    ok_all = True

    def record(name, passed, **d):
        nonlocal ok_all
        ok_all &= passed
        results.append({"scenario": name, "result": "PASS" if passed else "FAIL", **d})
        say(f"== {name}: {'PASS' if passed else 'FAIL'}")

    try:
        # 1. fresh install
        r = run(["sh", str(install)], env_fresh, name="fresh")
        record("fresh_install", r.returncode == 0 and "verification: OK" in r.stdout and "routed: 'auto' -> ollama/" in r.stdout
               and (home / "config.yaml").exists() and (home / "keys/api_keys").exists(),
               exit=r.returncode, config_created=(home / "config.yaml").exists())
        key_before = (home / "keys/api_keys").read_text()
        cfg_before = (home / "config.yaml").read_text()
        # 2. repeat install (existing config)
        r = run(["sh", str(install)], env_fresh, name="repeat")
        record("repeat_install_keeps_config", r.returncode == 0 and "existing configuration kept" in r.stdout and "verification: OK" in r.stdout
               and (home / "keys/api_keys").read_text() == key_before and (home / "config.yaml").read_text() == cfg_before,
               exit=r.returncode)
        # 3. unrelated listener on the configured port
        srv = ThreadingHTTPServer(("127.0.0.1", port), Foreign)
        threading.Thread(target=srv.serve_forever, daemon=True).start()
        Foreign.calls.clear()
        try:
            r = run(["sh", str(install)], env_fresh, name="foreign")
            sent_key = [c for c in Foreign.calls if c["authorization"]]
            record("unrelated_listener_is_a_collision", r.returncode != 0 and "not a ModelSaar gateway" in (r.stdout + r.stderr)
                   and not sent_key and all(c["path"] == "/healthz" for c in Foreign.calls),
                   exit=r.returncode, requests_seen=Foreign.calls, key_sent=bool(sent_key))
            # and `modelsaar test` alone refuses too
            r = run(["modelsaar", "test"], env_fresh, name="test-foreign")
            record("test_refuses_unrelated_listener", r.returncode != 0 and "not a ModelSaar gateway" in r.stderr and "No key was sent" in r.stderr,
                   exit=r.returncode)
        finally:
            srv.shutdown()
            srv.server_close()
        # 4./5. a running gateway (the first-use `modelsaar serve`), then test, installer reuse, client config
        say("\n$ modelsaar serve &   (first use after the installer: NOT `modelsaar init && modelsaar serve`)")
        gw = subprocess.Popen(["modelsaar", "serve"], env=env_fresh, stdout=open(out_dir / "serve.log", "w"), stderr=subprocess.STDOUT)
        try:
            deadline = time.monotonic() + 30
            up = False
            while time.monotonic() < deadline:
                try:
                    import httpx

                    hz = httpx.get(f"http://127.0.0.1:{port}/healthz", timeout=1)
                    if hz.status_code == 200 and hz.json().get("service") == "modelsaar":
                        up = True
                        break
                except Exception:
                    pass
                time.sleep(0.3)
            record("serve_starts_and_identifies_itself", up)
            r = run(["modelsaar", "init"], env_fresh, name="init-again")
            record("init_refuses_existing_config_so_the_site_must_not_chain_it", r.returncode != 0 and "already exists" in r.stderr, exit=r.returncode)
            r = run(["modelsaar", "test"], env_fresh, name="test")
            record("test_passes_with_attribution", r.returncode == 0 and "GET /healthz -> modelsaar" in r.stdout and "routed: 'auto' -> ollama/" in r.stdout and "request req_" in r.stdout, exit=r.returncode)
            r = run(["sh", str(install)], env_fresh, name="installer-with-running-gateway")
            record("installer_reuses_running_gateway", r.returncode == 0 and "already listening" in r.stdout and "identified by its health contract" in r.stdout
                   and "temporary gateway stopped" not in r.stdout and gw.poll() is None, exit=r.returncode)
            r = run(["modelsaar", "client-config", "open-webui"], env_fresh, name="client-config")
            record("client_config_open_webui_renders_from_running_gateway", r.returncode == 0 and f"127.0.0.1:{port}/v1" in r.stdout and "auto" in r.stdout, exit=r.returncode)
            # The key itself is never written to the transcript (even a throwaway fixture key).
            say(f"\n$ head -1 {home / 'keys/api_keys'}   (output redacted in this transcript)")
            key_line = subprocess.run(["sh", "-c", f"head -1 {shlex.quote(str(home / 'keys/api_keys'))}"], env=env_fresh, capture_output=True, text=True).stdout.strip()
            say(f"{key_line[:4]}… ({len(key_line)} characters, one line)")
            record("key_command_prints_a_pasteable_value", key_line.startswith("msk_") and "$(" not in key_line and "\n" not in key_line)
        finally:
            gw.terminate()
            try:
                gw.wait(timeout=10)
            except subprocess.TimeoutExpired:
                gw.kill()
    finally:
        fake.stop()
        (out_dir / "results.json").write_text(json.dumps(results, indent=2) + "\n")
        say(f"\nresults: {out_dir / 'results.json'}")
        log.close()
    print(json.dumps(results, indent=2))
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
